        <h2>Stone Town: Why It Is Worth Adding</h2>

        <p>
            Stone Town is the cultural heart of Zanzibar and is very different from the beach areas. It is best for travellers who want to understand Zanzibar beyond the ocean. The old town has narrow streets, carved wooden doors, spice history, old buildings, markets, rooftop restaurants and sunset views.
        </p>

        <ul class="znz-bullets">
            <li><strong>Best stay:</strong> 1 night is enough for a short visit, while 2 nights allow a more relaxed cultural experience.</li>
            <li><strong>Best activities:</strong> Stone Town walking tour, spice tour, Prison Island, local markets, Forodhani evening food experience and sunset dhow cruise.</li>
            <li><strong>Good timing:</strong> Stone Town works well before the beach stay or on the final night before departure.</li>
            <li><strong>Travel tip:</strong> If your international flight arrives late or departs early, Stone Town can be a practical first or last stop.</li>
        </ul>

