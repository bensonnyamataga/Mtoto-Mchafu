<section class="kili-section" id="summit-experience">
    <div class="kili-inner">
        <h2>What Happens Before the Summit Attempt?</h2>

        <p>
            The summit plan begins before climbers leave their base camp. After an early dinner, the guide briefs the group, checks clothing and equipment, and explains the expected pace. Climbers then rest for a few hours before being woken for final preparation.
        </p>

        <p>
            Most summit teams begin walking late at night, often around midnight. The exact departure time depends on the route, the group's walking speed, weather and each climber's condition. A slower group may leave earlier so that everyone has enough time without being forced to rush.
        </p>

        <p>
            Before departure, climbers put on their summit layers, organise their headlamps and take a light meal or warm drink. The atmosphere at camp is usually quiet. Everyone knows that the longest and most demanding part of the climb is about to begin.
        </p>

        <h2>How Long Does the Climb to the Summit Take?</h2>

        <p>
            Peter explains that many climbers take approximately six to seven hours to reach the crater rim or summit area, but this is not a fixed promise. Some people need more time, while a strong and well-acclimatised climber may move faster.
        </p>

        <p>
            The time depends on the route, health condition, walking pace, weather, rest stops and how the body is responding to altitude. A guide may deliberately slow the pace because arriving safely is more important than reaching a particular point at a particular time.
        </p>

        <div class="kili-note">
            <strong>Do not compete with other climbers.</strong> The correct summit pace is the pace that allows you to breathe steadily, communicate clearly and continue without exhausting your body too early.
        </div>
    </div>
</section>

