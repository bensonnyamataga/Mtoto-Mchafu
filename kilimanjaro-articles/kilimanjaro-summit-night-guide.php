<section class="kili-section">
    <div class="kili-inner">
        <h2>What to Wear on Kilimanjaro Summit Night</h2>

        <p>
            Summit night is not the time to test new equipment or discover that an important layer is wet. Clothing should be prepared before resting, and every item should be easy to find in the dark.
        </p>

        <div class="kili-card-grid">
            <div class="kili-card">
                <h4>Upper Body</h4>
                <p>Thermal base layer, warm fleece or insulated middle layer, down jacket and a windproof waterproof outer jacket.</p>
            </div>

            <div class="kili-card">
                <h4>Lower Body</h4>
                <p>Thermal leggings, warm trekking trousers and windproof or waterproof outer trousers when conditions require them.</p>
            </div>

            <div class="kili-card">
                <h4>Hands and Head</h4>
                <p>Thin inner gloves, insulated outer gloves, a warm hat or beanie, and a buff or balaclava to protect the face and neck.</p>
            </div>

            <div class="kili-card">
                <h4>Feet</h4>
                <p>Proper hiking boots and one clean, completely dry pair of heavy summit socks kept separately from the socks used on earlier days.</p>
            </div>
        </div>

        <p>
            Peter strongly recommends saving a dry pair of warm socks specifically for summit night. Damp or dirty socks hold moisture, and cold toes can quickly make walking uncomfortable.
        </p>

        <ul class="kili-bullets">
            <li>Use clothing layers that can be added or removed without emptying the whole daypack.</li>
            <li>Carry a headlamp with spare batteries.</li>
            <li>Keep sunglasses ready for sunrise and the descent.</li>
            <li>Protect drinking water from freezing.</li>
            <li>Avoid clothing or boots that are too tight because poor circulation can make hands and feet feel colder.</li>
        </ul>
    </div>
</section>

<section class="kili-section">
    <div class="kili-inner">
        <h2>What to Eat Before the Summit Climb</h2>

        <p>
            At high altitude, appetite may reduce and digestion can feel slower. For this reason, the meal before summit night should provide energy without being extremely heavy or oily.
        </p>

        <p>
            Dinner may include pasta, rice, potatoes, soup, vegetables or another warm and familiar meal. Heavy portions of meat are not normally the main focus because some climbers find them difficult to digest before a long night climb.
        </p>

        <p>
            Before departure, the crew normally provides a light meal or snack together with a warm drink. Tea, coffee, hot chocolate, porridge, toast, biscuits, popcorn, fruit or light soup may be offered depending on the camp menu.
        </p>

        <h2>Food and Drinks During the Summit Attempt</h2>

        <p>
            During short rest stops, climbers may take small amounts of quick energy food. Peter's team commonly carries simple snacks that are easy to eat even when the appetite is low.
        </p>

        <ul class="kili-bullets">
            <li>Chocolate, sweets or glucose-based snacks</li>
            <li>Biscuits or energy bars</li>
            <li>Dried fruit or a small sandwich</li>
            <li>Juice or an electrolyte drink</li>
            <li>Warm tea or another drink in an insulated flask</li>
        </ul>

        <p>
            Small sips and small bites are usually easier than trying to eat a full meal during the climb. Water bottles should be protected from freezing, and the guide will remind climbers to drink regularly.
        </p>

        <h2>Food After Returning to Base Camp</h2>

        <p>
            After the summit and descent, many climbers feel tired, cold and emotionally overwhelmed. The first priorities are changing into dry clothing, drinking something warm and resting briefly.
        </p>

        <p>
            A recovery meal may begin with tea, soup, juice or another warm drink, followed by carbohydrates and protein. Depending on the menu, this may include rice, pasta, potatoes, eggs, beans, chicken, vegetables, bread or fruit.
        </p>

        <p>
            Some climbers are not hungry immediately. In this case, the cook may offer soup, fruit or a smaller meal until the appetite returns. Climbers normally rest before continuing down to a lower camp, where the air is warmer and recovery becomes easier.
        </p>
    </div>
</section>

<section class="kili-section">
    <div class="kili-inner">
        <h2>The Most Common Summit-Night Mistakes</h2>

        <div class="kili-card-grid">
            <div class="kili-card">
                <h4>Walking Too Fast</h4>
                <p>Starting quickly uses energy early and increases breathing demand. Peter's advice is simple: listen to the guide and respect “pole pole.”</p>
            </div>

            <div class="kili-card">
                <h4>Wearing the Wrong Clothing</h4>
                <p>Missing thermal layers, wet socks, weak gloves or unsuitable outer clothing can turn manageable cold into a serious problem.</p>
            </div>

            <div class="kili-card">
                <h4>Hiding Health Changes</h4>
                <p>Some climbers stay silent because they fear being told to stop. Peter explains that honest communication gives the guide time to make the safest decision.</p>
            </div>

            <div class="kili-card">
                <h4>Thinking Only About the Summit</h4>
                <p>Uhuru Peak is the goal, but returning safely is part of the achievement. A guide may slow the pace, change the plan or recommend descent.</p>
            </div>
        </div>

        <div class="kili-note">
            <strong>Tell your guide the truth.</strong> Headache, dizziness, nausea, unusual weakness, confusion, breathing difficulty or a sudden change in condition should never be hidden.
        </div>
    </div>
</section>

<section class="kili-section">
    <div class="kili-inner">
        <h2>How Kilimanjaro Guides Motivate Tired Climbers</h2>

        <p>
            Motivation on Kilimanjaro is not always a loud speech. Sometimes it is a quiet reminder to take one more slow step. Sometimes it is the guide adjusting a layer, checking a glove or asking a climber to breathe calmly.
        </p>

        <p>
            Peter also uses music and familiar mountain songs to lift the mood. Songs such as “Jambo Bwana” and “Kilimanjaro Hakuna Matata” create a sense of teamwork and help climbers remember that they are not facing the mountain alone.
        </p>

        <p>
            A good guide understands the difference between encouraging a tired climber and pushing someone whose condition is becoming unsafe. The strongest motivation is built on trust: the climber speaks honestly, and the guide makes decisions based on experience.
        </p>
    </div>
</section>

