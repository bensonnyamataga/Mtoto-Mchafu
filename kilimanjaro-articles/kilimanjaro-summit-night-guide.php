        <h3>From Barafu Camp to Stella Point</h3>
        <p>
            Peter describes the upper section before Stella Point as one of the hardest parts of the Machame-side approach. By this stage, climbers have already walked for several hours. The air is thin, the temperature is low and the loose ground can make every step feel slow.
        </p>

        <h3>From Kibo Hut to Gilman's Point</h3>
        <p>
            The Marangu and Rongai approach has a long, rocky and demanding climb toward Gilman's Point. The final part can feel especially difficult because tired climbers must continue moving through cold conditions while maintaining a controlled pace.
        </p>

        <h3>From the Crater Rim to Uhuru Peak</h3>
        <p>
            Reaching Stella Point or Gilman's Point is a major achievement, but the climb is not finished. The trail around the crater rim is normally less steep, yet altitude and exhaustion can make the final distance to Uhuru Peak feel long.
        </p>

        <p>
            This is also the point where many climbers begin to feel emotionally stronger. Daylight appears, the summit becomes visible and the difficult night starts to make sense.
        </p>
