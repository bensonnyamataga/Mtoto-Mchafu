        <p>
            The guide interviewed for this content recommends the 8-day Lemosho option for many first-time climbers because it provides more time
            to move from lower elevations to higher camps. A longer itinerary can also be more suitable for large groups because each participant
            arrives with different mountain experience, walking speed and physical condition.
        </p>

        <p>
            Lemosho contains useful acclimatization patterns. Climbers may walk to a higher point during the day and descend to a lower sleeping elevation.
            The best-known example is the journey from Shira 2 toward Lava Tower at approximately 4,630 metres before descending to Barranco Camp at approximately 3,976 metres.
            This is commonly described as “climb high, sleep low.”
        </p>

