        <h2>Fitness and Mental Preparation</h2>

        <p>
            The guide interview emphasised that fitter climbers are more likely to enjoy the route rather than simply endure it.
            Good preparation allows a traveller to walk steadily, recover better, take photographs and participate in the social experience of the climb.
            However, high physical fitness does not create immunity from altitude illness.
        </p>

        <p>
            Training should normally include long walks, hill sessions, stair climbing, cardiovascular exercise, leg strength and back-to-back hiking days.
            Mental preparation is also important because summit night demands patience and the ability to continue at a slow pace in cold and uncomfortable conditions.
        </p>

        <h2>Altitude, Medication and Personal Health</h2>

        <p>
            Altitude response differs from one person to another and cannot be predicted only by age or fitness. Climbers should discuss the trip with a qualified doctor,
            particularly when they have a medical condition, use regular medication or are considering prescription altitude medication such as acetazolamide, commonly known as Diamox.
        </p>

        <div class="kili-note">
            <strong>Medical safety:</strong> A mountain guide is not a doctor and should not prescribe personal medication.
            Do not take medicine from another climber. Bring medication supplied or approved by your own healthcare professional,
            tell the guide what you are using and report any symptoms immediately.
        </div>

