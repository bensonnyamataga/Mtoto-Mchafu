        <h2>Scenery and Mountain Zones</h2>

        <p>
            Lemosho begins in a remote rainforest where colobus monkeys, blue monkeys and mountain birdlife may be encountered.
            The route then enters heath and moorland with giant heather, volcanic ridges and views across the Shira Plateau.
            Higher sections pass through alpine desert where vegetation becomes sparse and temperature changes become more severe.
        </p>

        <p>
            The southern circuit provides views of Kibo, glaciers, the Barranco Valley and Mawenzi in suitable weather.
            The summit zone is an arctic environment with exposed rock, ice, wind and temperatures that can fall well below freezing.
        </p>

        <h2>Accommodation and Camp Life</h2>

        <p>
