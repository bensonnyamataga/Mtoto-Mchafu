        <h2>Day-by-Day Lemosho Route Experience</h2>

        <h3>Day 1: Londorossi Gate to Mti Mkubwa Camp</h3>

        <p>
            The journey normally begins with a drive from Moshi or Arusha to Londorossi Gate at approximately 2,100 metres for registration,
            permit checks and crew preparation. A vehicle then continues toward the Lemosho trailhead. The first trek passes through montane rainforest
            to Mti Mkubwa, also called Big Tree or Forest Camp, at approximately 2,650 metres.
        </p>

        <p>
            This first day is usually a gentle introduction, but rain can make the trail muddy. Climbers should already carry waterproof layers in the daypack.
            The forest supports birds and primates, and wildlife signs may occasionally be seen, although sightings are never guaranteed.
        </p>

        <h3>Day 2: Mti Mkubwa Camp to Shira 1 Camp</h3>

        <p>
            The trail climbs out of the forest into tall heather and open moorland. The day gains approximately 850 metres of sleeping elevation,
            reaching Shira 1 Camp at around 3,500 metres. This is often the first day when climbers clearly feel the reduced oxygen and the need to follow a slow “Pole Pole” pace.
        </p>

        <p>
            As the vegetation opens, the group may receive its first broad view of Kibo across the Shira Plateau. The route includes rolling ridges,
            streams and steeper sections before descending slightly toward camp.
        </p>

        <h3>Day 3: Shira 1 Camp to Shira 2 Camp</h3>

        <p>
            The standard 8-day program allows time to cross the Shira Plateau gradually rather than rushing directly toward the higher mountain.
            Shira 2 Camp is commonly listed at approximately 3,850 metres. Depending on weather, pace and the selected itinerary,
            the guide may include an acclimatization walk toward Shira Cathedral or another higher point before returning to the sleeping camp.
        </p>

        <p>
            Cathedral Point is commonly measured at approximately 3,872 metres. It should not be confused with the highest remaining point of the wider Shira ridge,
            which is sometimes listed close to 3,962 metres. The purpose of the optional walk is the additional altitude exposure and scenery, not technical climbing.
        </p>

        <h3>Day 4: Shira 2 to Lava Tower and Barranco Camp</h3>

        <p>
            This is one of the most important acclimatization days. Climbers leave Shira 2 at approximately 3,850 metres and ascend through alpine desert toward
            Lava Tower at approximately 4,630 metres. After spending time at the higher point, the trail descends to Barranco Camp at approximately 3,976 metres.
        </p>

        <p>
            The combination of a high daytime point and lower sleeping camp follows the climb-high, sleep-low principle. The day can still be tiring,
            and some climbers may begin to experience altitude symptoms. Any symptoms should be reported to the guide immediately rather than hidden from the group.
        </p>

        <h3>Day 5: Barranco Wall to Karanga Camp</h3>

        <p>
            The day begins below the Barranco Wall. The ascent is steep and involves using hands for balance on some rocky sections,
            but it is normally a guided scramble rather than technical rock climbing. The guide controls spacing and shows each climber where to place hands and feet.
        </p>

        <p>
            After reaching the top, the route crosses a series of ridges and valleys toward Karanga Camp at approximately 3,995 metres.
            The total distance is short, but the changing terrain can make the day feel more demanding than the kilometre figure suggests.
        </p>

        <h3>Day 6: Karanga Camp to Barafu Camp</h3>

        <p>
            The trek continues through dry alpine desert to Barafu Camp at approximately 4,673 metres. “Barafu” means ice in Swahili,
            reflecting the cold upper-mountain conditions. Climbers normally arrive early enough to eat, organise summit clothing, prepare water and rest before the night ascent.
        </p>

        <p>
            This separate Karanga-to-Barafu stage is one of the main advantages of the 8-day itinerary. A compressed program may require a longer approach to Barafu,
            leaving less time to rest before the most difficult section of the climb.
        </p>

        <h3>Day 7: Barafu Camp to Uhuru Peak and Mweka Camp</h3>

        <p>
            Summit departure normally begins around midnight. Climbers ascend slowly through cold, dark and loose volcanic terrain toward Stella Point on the crater rim,
            commonly listed at approximately 5,756 metres. From Stella Point, the final trail continues around the rim to Uhuru Peak at 5,895 metres.
        </p>

        <p>
            After photographs and a short summit stop, the group descends to Barafu for a brief rest and continues to Mweka Camp at approximately 3,100 metres.
            This is normally the longest, coldest and most physically demanding day of the route, involving both a major ascent and a long descent.
        </p>

        <h3>Day 8: Mweka Camp to Mweka Gate</h3>

        <p>
            The final trek descends through rainforest to Mweka Gate at approximately 1,640 metres. The lower trail can be wet and slippery,
            so trekking poles and careful foot placement remain useful. After park formalities and summit certificates, the vehicle transfers the group back to Moshi or Arusha.
        </p>

