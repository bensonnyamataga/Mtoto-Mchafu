            <div>
                <h2>Tanzania Is Much Bigger Than Many Travellers Expect</h2>
                <p>One of the most common planning mistakes is assuming that Serengeti, Ngorongoro, Mount Kilimanjaro and Zanzibar are close to one another. They may appear together in travel photographs, but moving between them can take many hours and sometimes requires a domestic flight.</p>
                <p>A direct journey from Arusha toward Serengeti is not a short transfer. It is a major travel day that passes through towns, highlands and conservation areas before reaching the central plains. Northern Serengeti is farther again. Zanzibar is an island off Tanzania’s coast, so combining it with a northern safari normally involves a flight.</p>
                <p>We regularly see travellers request several distant destinations within only a few days. The itinerary may be technically possible, but too much time is then spent in transit rather than observing wildlife.</p>
                <div class="kili-note"><strong>Lesson:</strong> Plan with realistic driving and flight time, not only the names of destinations.</div>
            </div>
