    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const faqQuestions = document.querySelectorAll('.safari-faq-question');
            
            faqQuestions.forEach(question => {
                question.addEventListener('click', function() {
                    const answer = this.nextElementSibling;
                    const toggle = this.querySelector('.safari-faq-toggle i');
                    
                    // Toggle active class
                    answer.classList.toggle('active');
                    
                    // Change icon
                    if (answer.classList.contains('active')) {
                        toggle.classList.remove('fa-plus');
                        toggle.classList.add('fa-minus');
                    } else {
                        toggle.classList.remove('fa-minus');
                        toggle.classList.add('fa-plus');
                    }
                    
                    // Close other open FAQs (optional)
                    faqQuestions.forEach(q => {
                        if (q !== question) {
                            const otherAnswer = q.nextElementSibling;
                            const otherToggle = q.querySelector('.safari-faq-toggle i');
                            if (otherAnswer.classList.contains('active')) {
                                otherAnswer.classList.remove('active');
                                otherToggle.classList.remove('fa-minus');
                                otherToggle.classList.add('fa-plus');
                            }
                        }
                    });
                });
            });
        });
    </script>

