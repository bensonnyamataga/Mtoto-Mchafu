                        <h4>6. Optional Activities During Your Safari</h4>
                        <p>While your safari package includes extensive game drives and park experiences, optional activities can enrich your adventure and create unforgettable memories. These activities are not included in standard packages and require advance booking due to popularity and limited availability.</p>
                        
                        <p><strong>Hot Air Balloon Safari (USD 550-600 per person):</strong> Perhaps the most iconic optional activity, a balloon safari offers perspectives impossible to achieve any other way. You'll launch before dawn, rising silently above the Serengeti plains as the sun paints the landscape in golden hues. From above, you'll spot herds of animals moving across the savannah, their patterns and movements revealed in stunning clarity. The hour-long flight concludes with a champagne breakfast in the bush, complete with a certificate commemorating your adventure.</p>
                        
                        <p><strong>Maasai Village Visit (USD 50 per person):</strong> This cultural experience provides insight into the traditions and daily life of Tanzania's most famous tribe. You'll be welcomed with traditional singing and dancing, tour the village (manyatta), learn about Maasai customs, and have the opportunity to purchase authentic handicrafts directly from community members. The visit supports local communities and creates meaningful cultural exchange.</p>
                        
                        <p><strong>Walking Safari (USD 30-50 per person):</strong> Accompanied by an armed ranger and your guide, a walking safari takes you into the bush on foot, engaging senses that remain dormant in vehicles. You'll learn to track animals, identify plants and their uses, examine insect life, and appreciate the smaller details of the ecosystem. Walking safaris are available in certain areas and provide a completely different perspective on the African wilderness.</p>
                        
                        <p><strong>Night Game Drive (USD 80-100 per person):</strong> Available in private concessions outside national parks, night drives reveal the nocturnal world that remains hidden during standard safari hours. Using spotlights, you'll search for nightjars, genets, civets, springhares, and perhaps even leopard or lion on the hunt. The experience of hearing the bush come alive at night is unforgettable.</p>
                        
