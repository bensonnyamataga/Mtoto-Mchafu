                <h2>Northern Tanzania's Legendary Safari Circuit</h2>
                
                <p>The Northern Circuit comprises four primary parks, each offering distinct landscapes and wildlife experiences. Understanding their unique characteristics helps you appreciate why this region has captivated explorers for generations. Your lodge-based package will typically include three or four of these destinations, with the combination chosen to maximize your wildlife encounters within your available time.</p>
                
                <div class="day-images">
                    <img src="img/wildbeest-migration-mara-river.jpg" alt="Wildebeest migration crossing plains in Serengeti">
                    <img src="img/serengeti-lions-budget-safari.jpg" alt="Wildlife on Ngorongoro Crater floor">
                </div>
                
                <h3>Serengeti National Park</h3>
                <p>The Serengeti needs little introduction. Its name derives from the Maasai word "siringet," meaning "endless plains." Covering nearly 15,000 square kilometers, this UNESCO World Heritage Site protects one of the oldest and most complex ecosystems on Earth. The Serengeti's primary claim to fame is the Great Migration, an annual movement of 1.5 million wildebeest, 400,000 zebras, and 200,000 gazelles.</p>
                
                <p>For lodge-based safaris, the Central Serengeti (Seronera area) is the most convenient location with several excellent mid-range lodges perfectly positioned for game drives in this wildlife-rich area. You'll be close to the Seronera River, which attracts wildlife year-round, and within easy reach of the kopjes (rock outcroppings) where lions love to lounge.</p>
                
                <h3>Ngorongoro Crater</h3>
                <p>The Ngorongoro Crater represents one of Africa's most remarkable geological wonders. Formed when a massive volcano collapsed inward, the crater now forms a natural enclosure where approximately 25,000 large animals reside. The crater hosts one of Tanzania's last remaining populations of critically endangered black rhinos.</p>
                
                <p>For crater visits, you have two main lodge options: staying on the crater rim or in Karatu. Rim lodges offer spectacular views and early access to the crater floor. Karatu lodges offer better value and more comfortable accommodations at lower prices. We'll help you decide which option suits your budget and preferences.</p>
                
                <h3>Tarangire National Park</h3>
                <p>Tarangire rewards visitors with unique experiences and often uncrowded game viewing. Elephant herds of up to 300 individuals gather along the Tarangire River during the dry season, and ancient baobab trees create a distinctive landscape. Several comfortable lodges are available in and around the park.</p>
                
                <h3>Lake Manyara National Park</h3>
                <p>Compact yet incredibly diverse, Lake Manyara is famous for its tree-climbing lions and thousands of flamingos when conditions are right. Lodges perched on the escarpment offer spectacular views over the lake and the Rift Valley.</p>

